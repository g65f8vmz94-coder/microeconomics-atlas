function comparison(a,b) {
  return a>b?'豆浆在前':a<b?'包子在前':'并列';
}
function pivotalRow(k) {
  const profile = Array.from({length:3},(_,i)=>i<k?[1,0,2]:[0,2,1]);
  const {score}=aggregate(profile,'dictator',[2,1,0],1);
  const socialOrder=[0,1,2].sort((a,b)=>score[b]-score[a]);
  return [k,menuRank(profile[1]),menuRank(socialOrder)];
}
function ballot(report) {
  const profile=[report,[1,0,2],[0,1,2]];
  return [menuRank(report),aggregate(profile,'plurality').score.join('、'),menu[socialWinner(profile,'plurality')]];
}

