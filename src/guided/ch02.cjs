const join = xs => xs.join('、');
function best(menu, scores) {
  return menu.reduce((winner, x) => scores[x] > scores[winner] ? x : winner);
}
const dishes = {饺:3, 面:2, 粥:1};
const chooseDish = menu => [join(menu), best(menu, dishes)];
function middle(menu) { return menu[Math.floor((menu.length-1)/2)]; }
const order = ['甲','乙','丙','丁'];
const grades = {甲:4,乙:7,丙:9,丁:3};
function screen(menu, cutoff, highestFallback = false) {
  const list = order.filter(x => menu.includes(x));
  const first = list.find(x => grades[x] >= cutoff);
  return first ?? (highestFallback ? best(list,grades) : list.at(-1));
}
function screeningRow(menu, cutoff, highestFallback = false) {
  return [join(menu),cutoff,screen(menu,cutoff,highestFallback)];
}
const fee = 1;
const wallet = n => 12 - n*fee;
const ordered = ['A','B','C'];
const scores = {A:2,B:1,C:3};
function firstPeak(menu) {
  const list = ordered.filter(x => menu.includes(x));
  const peak = list.find((x,i) => i+1 < list.length && scores[x]>scores[list[i+1]]);
  return peak ?? list.at(-1);
}

