function fraction12(x) {
  const numerator=Math.round(12*x);
  const gcd=(a,b)=>b?gcd(b,a%b):a;
  const f=gcd(numerator,12);
  return f===12?numerator/12:'$\\frac{'+numerator/f+'}{'+12/f+'}$';
}
