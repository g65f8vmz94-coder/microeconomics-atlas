const round=x=>Number(x.toFixed(5));
const amounts=(...xs)=>'（'+xs.map(round).join('，')+'）';
function unit(title,given,columns,frames,proof,practice,visual={}){
  return {title,given,columns,frames,proof,practice,...visual};
}
function trustPay(x,y){return amounts(10-x+y,3*x-y);}
function teamChoice(second){
  const next=second==='分账A'?[0,2]:[2,2];
  const enter=next[0]>1;
  return [second,amounts(...next),enter?'一起做':'各做各的',amounts(...(enter?next:[1,1]))];
}
function offerShares(alpha,beta){
  const first=(1-beta)/(1-alpha*beta);
  return [first,1-first,alpha*first,1-alpha*first];
}
