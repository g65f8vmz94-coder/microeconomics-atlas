'use strict';

const R = String.raw;
const cost = ([p,q], [x,y]) => p*x + q*y;
const round = x => Number(x.toFixed(3));
const pair = (x,y) => '（'+round(x)+'，'+round(y)+'）';
const budget = (w,p,q,x) => (w-p*x)/q;
const cd = (w,p,q,a) => [a*w/p,(1-a)*w/q];
const basket = (p,w,x) => [x, budget(w,...p,x), w];
const optimumProduct = x => x*budget(12,2,1,x);
const budgetXs = [0, 2, 5, 6];
const cdReceipt = (p,q,w,a) => {
  const [x,y] = cd(w,p,q,a);
  return [pair(p,q), w, pair(x,y), round(p*x)];
};
const cheaper = (p,q,w) => p===q ? [w/(2*p),w/(2*q)] : p<q ? [w/p,0] : [0,w/q];
function splitCase(p,q,w) {
  const result = cheaper(p,q,w);
  return [pair(p,q),pair(...result),round(result[0]+result[1])];
}

