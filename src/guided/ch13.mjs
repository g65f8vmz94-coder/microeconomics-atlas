function healthChoice(){
  let lo=0,hi=5;
  for(let i=0;i<60;i++){
    const y=(lo+hi)/2;
    if((10-2*y)*.35*Math.exp(-y)>2*healthChance(y,y))lo=y;
    else hi=y;
  }
  return (lo+hi)/2;
}
