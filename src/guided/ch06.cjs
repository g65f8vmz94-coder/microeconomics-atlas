function bestStaff(weight) {
  const scored=payroll.map(([n,profit])=>({n,profit,score:profit-weight*(196-n)}));
  const best=scored.reduce((a,b)=>a.score>b.score?a:b);
  return [weight,best.n,196-best.n,best.profit];
}
